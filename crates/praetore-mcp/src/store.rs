//! The local praetore-mcp home: LOCAL/DEV keys, signed authority, trust pins
//! in `praetore-verify` formats, the policy, and the receipts journal.

use praetore_core::{
    AgentId, AgentIdentity, AgentKeyPair, Authority, EvidenceAttesterKey, Policy, PolicyEffect,
    PolicyRule, TrustedAuthorityIssuer, authority::Validity,
};
use rand_core::{OsRng, RngCore};
use serde::{Deserialize, Serialize};
use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
};
use time::{Duration, OffsetDateTime, format_description::well_known::Rfc3339};
use zeroize::Zeroizing;

pub const ISSUER_NAME: &str = "praetore-mcp-local-issuer";
pub const CAPABILITY: &str = "mcp:tools/call";
pub const ACTION_TYPE: &str = "mcp.tools/call";
pub const AUDIENCE: &str = "praetore-mcp-local";
pub const DEFAULT_POLICY_ID: &str = "praetore-mcp-default";
pub const DEFAULT_ALLOW_RULE: &str = "allow-all-mcp-tool-calls";
const KEY_WARNING: &str = "PRAETORE LOCAL/DEV KEY generated by `praetore-mcp init`. NOT FOR PRODUCTION. Do not share, commit, or reuse.";
/// HighAssurance rejects authorities longer than 365 days.
const AUTHORITY_LIFETIME: Duration = Duration::days(364);

/// Resolves the home directory: `--dir`, then `PRAETORE_MCP_HOME`, then
/// `~/.praetore/mcp`.
pub fn resolve_home(dir: Option<&Path>) -> Result<PathBuf, String> {
    if let Some(dir) = dir {
        return absolute(dir);
    }
    if let Some(env) = std::env::var_os("PRAETORE_MCP_HOME").filter(|value| !value.is_empty()) {
        return absolute(Path::new(&env));
    }
    let home = user_home().ok_or("cannot determine the home directory; pass --dir")?;
    Ok(home.join(".praetore").join("mcp"))
}

pub fn user_home() -> Option<PathBuf> {
    let var = if cfg!(windows) { "USERPROFILE" } else { "HOME" };
    std::env::var_os(var)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
}

fn absolute(path: &Path) -> Result<PathBuf, String> {
    if path.is_absolute() {
        Ok(path.to_path_buf())
    } else {
        std::env::current_dir()
            .map(|cwd| cwd.join(path))
            .map_err(|e| format!("cannot resolve current directory: {e}"))
    }
}

#[derive(Debug, Clone)]
pub struct Home {
    pub root: PathBuf,
}

impl Home {
    pub fn new(root: PathBuf) -> Self {
        Self { root }
    }
    pub fn keys_dir(&self) -> PathBuf {
        self.root.join("keys")
    }
    pub fn issuer_key(&self) -> PathBuf {
        self.keys_dir().join("issuer.local-dev.key")
    }
    pub fn agent_key(&self) -> PathBuf {
        self.keys_dir().join("agent.local-dev.key")
    }
    pub fn attester_key(&self) -> PathBuf {
        self.keys_dir().join("attester.local-dev.key")
    }
    pub fn agent(&self) -> PathBuf {
        self.root.join("agent.json")
    }
    pub fn authority(&self) -> PathBuf {
        self.root.join("authority.json")
    }
    pub fn issuer_pins(&self) -> PathBuf {
        self.root.join("issuer-pins.jsonl")
    }
    pub fn attester_pin(&self) -> PathBuf {
        self.root.join("attester-public-key.hex")
    }
    pub fn policy(&self) -> PathBuf {
        self.root.join("policy.json")
    }
    pub fn receipts_dir(&self) -> PathBuf {
        self.root.join("receipts")
    }

    fn all_files(&self) -> Vec<PathBuf> {
        vec![
            self.issuer_key(),
            self.agent_key(),
            self.attester_key(),
            self.agent(),
            self.authority(),
            self.issuer_pins(),
            self.attester_pin(),
            self.policy(),
        ]
    }

    pub fn is_initialized(&self) -> bool {
        self.all_files().iter().all(|path| path.exists())
    }
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct KeyFile {
    warning: String,
    role: String,
    algorithm: String,
    secret_key_hex: String,
}

pub enum InitOutcome {
    Created,
    AlreadyInitialized,
}

/// Creates the home. Never overwrites: a fully initialized home is left
/// untouched; a partially initialized one is an error.
pub fn init(home: &Home) -> Result<InitOutcome, String> {
    if home.is_initialized() {
        return Ok(InitOutcome::AlreadyInitialized);
    }
    let existing: Vec<String> = home
        .all_files()
        .into_iter()
        .filter(|path| path.exists())
        .map(|path| path.display().to_string())
        .collect();
    if !existing.is_empty() {
        return Err(format!(
            "refusing to overwrite a partially initialized home; existing files:\n  {}\nmove them away or use a different --dir",
            existing.join("\n  ")
        ));
    }

    ensure_dir(&home.root, true)?;
    ensure_dir(&home.keys_dir(), false)?;
    ensure_dir(&home.receipts_dir(), false)?;

    let issuer_secret = random_secret();
    let agent_secret = random_secret();
    let attester_secret = random_secret();
    let issuer_key = AgentKeyPair::from_secret_bytes(&issuer_secret);
    let agent_key = AgentKeyPair::from_secret_bytes(&agent_secret);
    let attester_key = EvidenceAttesterKey::from_secret_bytes(&attester_secret);

    let now = OffsetDateTime::now_utc();
    let validity = Validity {
        not_before: Some(timestamp(now - Duration::minutes(5))?),
        not_after: Some(timestamp(now - Duration::minutes(5) + AUTHORITY_LIFETIME)?),
    };
    let agent = agent_key.identity(AgentId::new());
    let mut authority = Authority::new(agent.id.clone(), ISSUER_NAME, vec![CAPABILITY.into()])
        .with_validity(validity.clone());
    authority
        .sign_for_agent(&issuer_key, &agent)
        .map_err(|e| format!("cannot sign authority: {e}"))?;
    let pin = TrustedAuthorityIssuer::new(ISSUER_NAME, issuer_key.public_key())
        .and_then(|pin| pin.with_validity(validity))
        .map_err(|e| format!("cannot build issuer pin: {e}"))?;
    let policy = default_policy();
    policy
        .validate()
        .map_err(|e| format!("default policy invalid: {e}"))?;

    write_secret(home.issuer_key(), "issuer", &issuer_secret)?;
    write_secret(home.agent_key(), "agent", &agent_secret)?;
    write_secret(home.attester_key(), "evidence-attester", &attester_secret)?;
    write_new(&home.agent(), &to_pretty(&agent)?, 0o644)?;
    write_new(&home.authority(), &to_pretty(&authority)?, 0o644)?;
    let pin_line = pin
        .export_pin_json()
        .map_err(|e| format!("cannot export issuer pin: {e}"))?;
    write_new(&home.issuer_pins(), &format!("{pin_line}\n"), 0o644)?;
    let attester_public = attester_key
        .public_key()
        .map_err(|e| format!("attester key invalid: {e}"))?;
    write_new(
        &home.attester_pin(),
        &format!("{}\n", hex::encode(attester_public.as_bytes())),
        0o644,
    )?;
    write_new(&home.policy(), &to_pretty(&policy)?, 0o644)?;
    Ok(InitOutcome::Created)
}

/// The default policy (format 2, semantics v2): one ALLOW rule for every
/// `tools/call`, with `mcp.tools/call` declared Mission, gated on the
/// explicit `mcp:tools/call` capability. Users add DENY / REQUIRE_APPROVAL
/// rules keyed on `server`, `tool`, `arguments` and `arguments.<key>`.
pub fn default_policy() -> Policy {
    Policy::new_v2(
        DEFAULT_POLICY_ID,
        1,
        vec![
            PolicyRule::new(DEFAULT_ALLOW_RULE, ACTION_TYPE, PolicyEffect::Allow)
                .with_capability(CAPABILITY),
        ],
    )
    // G7: every MCP `tools/call` is a mission action. A tool named
    // `safety:...` is a safety action only if the policy declares it Safety.
    .with_mission_actions([ACTION_TYPE])
}

fn to_pretty<T: Serialize>(value: &T) -> Result<String, String> {
    serde_json::to_string_pretty(value)
        .map(|text| text + "\n")
        .map_err(|e| format!("serialization failed: {e}"))
}

fn timestamp(value: OffsetDateTime) -> Result<String, String> {
    value
        .replace_nanosecond(0)
        .map_err(|e| e.to_string())?
        .format(&Rfc3339)
        .map_err(|e| e.to_string())
}

fn random_secret() -> Zeroizing<[u8; 32]> {
    let mut secret = Zeroizing::new([0u8; 32]);
    OsRng.fill_bytes(secret.as_mut());
    secret
}

fn write_secret(path: PathBuf, role: &str, secret: &[u8; 32]) -> Result<(), String> {
    let file = KeyFile {
        warning: KEY_WARNING.into(),
        role: role.into(),
        algorithm: "ed25519".into(),
        secret_key_hex: hex::encode(secret),
    };
    let text = Zeroizing::new(to_pretty(&file)?);
    // Wipe the hex copy of the secret held by the struct.
    drop(Zeroizing::new(file.secret_key_hex));
    write_new(&path, &text, 0o600)
}

/// Writes a file that must not exist yet (O_EXCL), with Unix `mode`.
fn write_new(path: &Path, contents: &str, mode: u32) -> Result<(), String> {
    let mut options = fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(mode);
    }
    #[cfg(not(unix))]
    let _ = mode;
    let mut file = options
        .open(path)
        .map_err(|e| format!("cannot create {}: {e}", path.display()))?;
    file.write_all(contents.as_bytes())
        .and_then(|()| file.sync_all())
        .map_err(|e| format!("cannot write {}: {e}", path.display()))
}

/// Ensures `path` is a directory. Directories this tool creates get 0700
/// at creation (including missing parents); an existing directory is used
/// as is and never chmod-ed. With `allow_symlink == false`, a symlink at
/// `path` is refused instead of followed.
pub fn ensure_dir(path: &Path, allow_symlink: bool) -> Result<(), String> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() && !allow_symlink => Err(format!(
            "{} is a symlink; refusing to follow it",
            path.display()
        )),
        Ok(_) if path.is_dir() => Ok(()),
        Ok(_) => Err(format!("{} exists and is not a directory", path.display())),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            let mut builder = fs::DirBuilder::new();
            builder.recursive(true);
            #[cfg(unix)]
            {
                use std::os::unix::fs::DirBuilderExt;
                builder.mode(0o700);
            }
            builder
                .create(path)
                .map_err(|e| format!("cannot create {}: {e}", path.display()))
        }
        Err(error) => Err(format!("cannot stat {}: {error}", path.display())),
    }
}

/// Everything `wrap` and `verify` need, loaded from the home.
pub struct LoadedHome {
    pub agent_key: AgentKeyPair,
    pub agent: AgentIdentity,
    pub authority: Authority,
    pub attester_key: EvidenceAttesterKey,
    pub attester_public_key: praetore_core::VerifiedPublicKey,
    pub issuer_pins: Vec<TrustedAuthorityIssuer>,
    pub policy: Policy,
}

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("cannot read {}: {e}", path.display()))
}

fn read_secret(path: &Path, role: &str) -> Result<Zeroizing<[u8; 32]>, String> {
    check_secret_permissions(path)?;
    let text = Zeroizing::new(read(path)?);
    let file: KeyFile = serde_json::from_str(&text)
        .map_err(|_| format!("{} is not a praetore-mcp key file", path.display()))?;
    let hex_secret = Zeroizing::new(file.secret_key_hex);
    if file.role != role || file.algorithm != "ed25519" {
        return Err(format!(
            "{} has role/algorithm {}/{}, expected {role}/ed25519",
            path.display(),
            file.role,
            file.algorithm
        ));
    }
    let bytes = Zeroizing::new(
        hex::decode(hex_secret.as_bytes())
            .map_err(|_| format!("{} has an invalid secret", path.display()))?,
    );
    let mut secret = Zeroizing::new([0u8; 32]);
    if bytes.len() != 32 {
        return Err(format!("{} has an invalid secret length", path.display()));
    }
    secret.copy_from_slice(&bytes);
    Ok(secret)
}

#[cfg(unix)]
fn check_secret_permissions(path: &Path) -> Result<(), String> {
    use std::os::unix::fs::PermissionsExt;
    let mode = fs::metadata(path)
        .map_err(|e| format!("cannot read {}: {e}", path.display()))?
        .permissions()
        .mode();
    if mode & 0o077 != 0 {
        return Err(format!(
            "{} is accessible by group/others (mode {:o}); run: chmod 600 {}",
            path.display(),
            mode & 0o777,
            path.display()
        ));
    }
    Ok(())
}

#[cfg(not(unix))]
fn check_secret_permissions(_path: &Path) -> Result<(), String> {
    Ok(())
}

pub fn read_attester_pin(path: &Path) -> Result<praetore_core::VerifiedPublicKey, String> {
    let text = read(path)?;
    let bytes = hex::decode(text.trim())
        .map_err(|_| format!("{} is not a hex public key", path.display()))?;
    praetore_core::VerifiedPublicKey::from_bytes(&bytes)
        .map_err(|e| format!("{} is not a valid Ed25519 key: {e}", path.display()))
}

pub fn read_issuer_pins(path: &Path) -> Result<Vec<TrustedAuthorityIssuer>, String> {
    let pins = read(path)?
        .lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| {
            TrustedAuthorityIssuer::from_pin_json(line)
                .map_err(|e| format!("{}: invalid issuer pin: {e}", path.display()))
        })
        .collect::<Result<Vec<_>, _>>()?;
    if pins.is_empty() {
        return Err(format!("{} has no issuer pins", path.display()));
    }
    Ok(pins)
}

pub fn load_policy(home: &Home) -> Result<Policy, String> {
    Policy::from_json(&read(&home.policy())?).map_err(|e| {
        let hint = match e {
            praetore_core::PraetoreError::PolicyFormatUnsupported { found: 1, .. } => format!(
                " (policy format 1, written before G7: add \"format_version\": 2 and \"action_classes\": {{\"{ACTION_TYPE}\": \"Mission\"}}, or run `praetore policy classify --policy {}` to propose the table)",
                home.policy().display()
            ),
            _ => String::new(),
        };
        format!("{}: invalid policy: {e}{hint}", home.policy().display())
    })
}

pub fn load(home: &Home) -> Result<LoadedHome, String> {
    if !home.is_initialized() {
        return Err(format!(
            "{} is not initialized; run `praetore-mcp init --dir {}`",
            home.root.display(),
            home.root.display()
        ));
    }
    let agent_secret = read_secret(&home.agent_key(), "agent")?;
    let agent_key = AgentKeyPair::from_secret_bytes(&agent_secret);
    let attester_secret = read_secret(&home.attester_key(), "evidence-attester")?;
    let attester_key = EvidenceAttesterKey::from_secret_bytes(&attester_secret);
    let agent = AgentIdentity::from_json(&read(&home.agent())?)
        .map_err(|e| format!("{}: {e}", home.agent().display()))?;
    if agent
        .verified_public_key()
        .map_err(|e| format!("{}: {e}", home.agent().display()))?
        != agent_key.public_key()
    {
        return Err("agent.json does not match the agent key".into());
    }
    let authority = Authority::from_json(&read(&home.authority())?)
        .map_err(|e| format!("{}: {e}", home.authority().display()))?;
    let attester_public_key = read_attester_pin(&home.attester_pin())?;
    if attester_key
        .public_key()
        .map_err(|e| format!("attester key: {e}"))?
        != attester_public_key
    {
        return Err("attester-public-key.hex does not match the attester key".into());
    }
    Ok(LoadedHome {
        agent_key,
        agent,
        authority,
        attester_key,
        attester_public_key,
        issuer_pins: read_issuer_pins(&home.issuer_pins())?,
        policy: load_policy(home)?,
    })
}
